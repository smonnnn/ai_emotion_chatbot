# Emotion-Finetuned Chatbot

A simple chatbot that is finetuned to act like in an emotional manner.

## Setup

1. If needed, modify setup.sh to install the right pytorch version for your machine.
2. Run the setup script with `bash ./setup.sh`.
4. Enable the generated venv with source. /.venv/bin/activate.
5. Run `python main.py` to train the model.
6. Run `python chat.py` to chat with the model.